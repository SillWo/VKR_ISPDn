FSTEK21_MEASURES = [
    {
        "code": code,
        "section_code": section_code,
        "section_title": _SECTION_TITLES[section_code],
        "content": content,
        "levels": {4: level_4, 3: level_3, 2: level_2, 1: level_1},
    }
    for section_code, code, content, level_4, level_3, level_2, level_1 in _MEASURE_ROWS
]

_MEASURES_BY_CODE = {measure["code"]: measure for measure in FSTEK21_MEASURES}


def get_measure_by_code(code: str) -> dict | None:
    return _MEASURES_BY_CODE.get(code)


def get_measures_for_level(level: int) -> list[dict]:
    _validate_security_level(level)
    return [measure for measure in FSTEK21_MEASURES if measure["levels"][level]]


def get_measure_regulatory_status(measure_code: str, security_level: int) -> SecurityMeasureRegulatoryStatus:
    _validate_security_level(security_level)
    measure = get_measure_by_code(measure_code)
    if measure is None:
        raise KeyError(measure_code)
    return "base_set" if measure["levels"][security_level] else "not_base_set"


def _validate_security_level(level: int) -> None:
    if level not in {1, 2, 3, 4}:
        raise ValueError("security_level must be one of 1, 2, 3, 4")
